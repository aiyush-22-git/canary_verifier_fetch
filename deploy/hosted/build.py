"""Generate one paste-ready `agent.py` per Canary agent for the Agentverse hosted code editor.

    uv run python deploy/hosted/build.py                       # writes deploy/hosted/dist/<agent>/agent.py
    uv run python deploy/hosted/build.py --addresses a.json    # {"judge": "agent1q...", ...}: needed by the orchestrator

Each agent.py is self-contained: the modules it needs are embedded as strings and served by a tiny import hook, so the
code runs unchanged (`from core import chat, config` still works) and there is nothing else to upload. The files hold
your API keys (read from the root .env), so dist/ is git-ignored: paste them into Agentverse and do not share them.
Full steps: docs/HOSTED.md.
"""

from __future__ import annotations

import argparse
import ast
import base64
import json
import re
import sys
import time
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from core import config  # noqa: E402

DIST = ROOT / "deploy" / "hosted" / "dist"
PACKAGES = ("core", "agents", "targets", "tests")
LIMIT = 100_000  # Agentverse hosted code: "keep code under 100KB"

# agent key -> (entry module attach lines, secrets it needs)
ENTRY: dict[str, tuple[str, tuple[str, ...]]] = {
    "orchestrator": (
        "from agents.orchestrator import build_orchestrator\nbuild_orchestrator(agent=agent)",
        ("ASI1_API_KEY", "PAYMENT_RAIL", "AUDIT_TIMEOUT_S", "PROBE_TIMEOUT_S"),
    ),
    "judge": ("from agents.judge import build_judge\nbuild_judge(agent=agent)", ("ASI1_API_KEY",)),
    "probe-injection": ('from agents.probe import attach\nattach(agent, "injection")', ()),
    "probe-leak": ('from agents.probe import attach\nattach(agent, "leak")', ()),
    "probe-payment": ('from agents.probe import attach\nattach(agent, "payment")', ()),
    "target-leaky": ('from agents.target import attach\nattach(agent, "target-leaky")', ("ASI1_API_KEY",)),
    "target-overcharger": ('from agents.target import attach\nattach(agent, "target-overcharger")', ("ASI1_API_KEY",)),
    "target-solid": ('from agents.target import attach\nattach(agent, "target-solid")', ("ASI1_API_KEY",)),
    # not part of Canary: a hosted ASI:One stand-in that tests and hammers the live Orchestrator (tests/hosted_tester.py)
    "tester": ("from tests.hosted_tester import attach\nattach(agent)", ("TESTER_VERSION", "TESTER_SCRIPT")),
}


def agent_name(key: str) -> str:
    return config.AGENTS[key].name if key in config.AGENTS else "Canary-Tester"

LOADER = '''\
# --- import hook: serves the embedded Canary modules (generated by deploy/hosted/build.py) ---
import importlib.abc
import importlib.util
import sys

class _CanaryLoader(importlib.abc.Loader, importlib.abc.MetaPathFinder):
    def find_spec(self, name, path=None, target=None):
        if name in _SRC:
            return importlib.util.spec_from_loader(name, self, is_package=name in _PKGS)
        return None

    def create_module(self, spec):
        return None

    def exec_module(self, module):
        module.__file__ = "/hosted/" + module.__name__.replace(".", "/") + ".py"
        exec(compile(_SRC[module.__name__], module.__file__, "exec"), module.__dict__)

sys.meta_path.insert(0, _CanaryLoader())
'''

ENTRY_TMPL = '''
# --- start-up: the platform provides `agent`; the registry lives in the agent's own storage ---
try:
    agent
except NameError:
    from uagents import Agent
    agent = Agent()

try:
    from core import llm as _llm
    _llm.LOGGER = agent._logger
except Exception:
    pass
{registry}{attach}
'''

REGISTRY_LINES = "from core import registry\nregistry.bind_store(agent.storage)\n"
USES_REGISTRY = ("orchestrator", "judge")


def module_path(name: str) -> Path | None:
    p = ROOT.joinpath(*name.split("."))
    if p.with_suffix(".py").is_file():
        return p.with_suffix(".py")
    return None


def imports_of(source: str) -> set[str]:
    found: set[str] = set()
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, ast.Import):
            found |= {a.name for a in node.names if a.name.split(".")[0] in PACKAGES}
        elif isinstance(node, ast.ImportFrom) and node.module and node.level == 0:
            top = node.module.split(".")[0]
            if top not in PACKAGES:
                continue
            found.add(node.module)
            for a in node.names:  # `from core import chat` imports the submodule core.chat
                if module_path(f"{node.module}.{a.name}"):
                    found.add(f"{node.module}.{a.name}")
    return found


def minify(source: str) -> str:
    """Drop docstrings and comments (same behaviour, about 25% smaller): the hosted editor has a size limit."""
    tree = ast.parse(source)
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            first = node.body[0] if node.body else None
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value, str):
                node.body = node.body[1:] or [ast.Pass()]
    return ast.unparse(tree) + "\n"


def literal(text: str) -> str:
    """An exact, compact triple-quoted literal (backslashes and ''' escaped), far smaller than repr()."""
    if "\r" in text:
        return repr(text)
    return "'''" + text.replace("\\", "\\\\").replace("'''", "\\'\\'\\'") + "'''"


def closure(entry_modules: set[str]) -> dict[str, str]:
    """Every project module the entry modules import, transitively, as {dotted name: source}."""
    todo, seen, sources = sorted(entry_modules), set(), {}
    while todo:
        name = todo.pop()
        if name in seen:
            continue
        seen.add(name)
        path = module_path(name)
        if path is None:
            continue
        raw = path.read_text(encoding="utf-8")
        sources[name] = minify(raw)
        todo += sorted(imports_of(raw) - seen)
    return sources


HOSTED_DEFAULTS = {
    # Every hop between hosted agents takes 3 to 10 s, so the local defaults (80 s audit, 15 s per case) always time out.
    "AUDIT_TIMEOUT_S": "240",
    "PROBE_TIMEOUT_S": "45",
}


def read_env() -> dict[str, str]:
    env: dict[str, str] = {}
    for folder in (ROOT, *ROOT.parents):
        if (folder / ".env").is_file():
            for line in (folder / ".env").read_text().splitlines():
                m = re.match(r"^([A-Z0-9_]+)=(.*)$", line.strip())
                if m:
                    env[m.group(1)] = m.group(2).strip().strip("'\"")
            break
    for key, value in HOSTED_DEFAULTS.items():
        env[key] = env.get(key) or value
    return env


def data_module(key: str) -> str:
    """Only the data an agent reads: the Orchestrator plans from the packs, the targets run on profiles + store."""
    role = config.AGENTS[key].role if key in config.AGENTS else "tester"
    packs = {p.name: p.read_text(encoding="utf-8") for p in sorted((ROOT / "packs").glob("*.yaml"))} if role == "orchestrator" else {}
    profiles, store = ROOT / "targets" / "profiles.yaml", ROOT / "targets" / "store.json"
    prof = profiles.read_text(encoding="utf-8") if role == "target" and profiles.is_file() else ""
    sto = store.read_text(encoding="utf-8") if role == "target" and store.is_file() else "{}"
    return f"PACKS = {packs!r}\nPROFILES = {prof!r}\nSTORE = {sto!r}\n"


def build_agent(key: str, addresses: dict[str, str], env: dict[str, str]) -> tuple[str, list[str]]:
    attach, secret_keys = ENTRY[key]
    entry_modules = imports_of(attach)
    registry = REGISTRY_LINES if key in USES_REGISTRY else ""
    sources = closure(entry_modules | {"core.config"} | ({"core.registry"} if registry else set()))
    for pkg in PACKAGES:
        sources.setdefault(pkg, "")
    missing = [k for k in secret_keys if not env.get(k)]
    sources["hosted_addresses"] = f"ADDRESSES = {addresses!r}\n"
    sources["hosted_secrets"] = f"SECRETS = { {k: env[k] for k in secret_keys if env.get(k)}!r}\n"
    sources["bundle_data"] = data_module(key)
    head = f'"""Canary: {agent_name(key)}. Generated by deploy/hosted/build.py; paste into the Agentverse hosted editor."""\n\n'
    tail = LOADER + ENTRY_TMPL.format(registry=registry, attach=attach)
    plain = head + f"_PKGS = {sorted(PACKAGES)!r}\n_SRC = {{\n" + "".join(
        f"    {name!r}: {literal(src)},\n" for name, src in sources.items()) + "}\n\n" + tail
    if len(plain.encode()) <= LIMIT:
        return plain, missing
    # Over the editor's size limit: ship the modules zlib-compressed (about a third of the size, same behaviour).
    blob = base64.b64encode(zlib.compress(json.dumps(sources).encode(), 9)).decode()
    wrapped = "\n".join(blob[i:i + 100] for i in range(0, len(blob), 100))
    packed = (head + "import base64\nimport json\nimport zlib\n\n" + f"_PKGS = {sorted(PACKAGES)!r}\n"
              + '_SRC = json.loads(zlib.decompress(base64.b64decode("".join("""\n' + wrapped + '\n""".split()))))\n\n' + tail)
    return packed, missing


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--addresses", help="JSON file {agent key: agent1q... address} of the hosted agents")
    ap.add_argument("--only", help="build just this agent key")
    args = ap.parse_args()
    addresses = json.loads(Path(args.addresses).read_text()) if args.addresses else {}
    env = read_env()
    env["PAYMENT_RAIL"] = "free"  # hosted demo: free audits against malicious inputs, no payment rail
    env["TESTER_VERSION"] = str(int(time.time()))  # a new build makes the tester run its script again
    keys = [args.only] if args.only else [k for k in ENTRY if k != "tester"]
    DIST.mkdir(parents=True, exist_ok=True)
    problems = 0
    for key in keys:
        code, missing = build_agent(key, addresses, env)
        out = DIST / key
        out.mkdir(exist_ok=True)
        (out / "agent.py").write_text(code, encoding="utf-8")
        readme = ROOT / "docs" / "agentverse" / f"{key.split('-')[0]}.md"
        if readme.is_file():
            (out / "README.md").write_text(readme.read_text(encoding="utf-8"), encoding="utf-8")
        size = len(code.encode())
        flag = "  <-- over 100KB: tell me, I'll split it" if size > LIMIT else ""
        note = f"  (empty in .env: {', '.join(missing)})" if missing else ""
        problems += bool(flag)
        print(f"{agent_name(key):<26} {size / 1000:6.1f} KB  {out / 'agent.py'}{flag}{note}")
    if key == "orchestrator" or "orchestrator" in keys:
        absent = [k for k in ENTRY if k != "orchestrator" and k not in addresses]
        if absent:
            print(f"\nThe orchestrator needs the other agents' addresses (missing: {', '.join(absent)}).")
            print("Create those agents first, put their addresses in a JSON file, and re-run with --addresses.")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
