"""Generate one paste-ready `agent.py` per Canary agent for the Agentverse hosted code editor.

    uv run python deploy/hosted/build.py                       # writes deploy/hosted/dist/<agent>/agent.py
    uv run python deploy/hosted/build.py --addresses a.json    # {"judge": "agent1q...", ...}: needed by the orchestrator

Each agent.py is self-contained: the modules it needs are embedded as strings and served by a tiny import hook, so the
code runs unchanged (`from core import chat, config` still works) and there is nothing else to upload. The files hold
your API keys (read from the root .env), so dist/ is git-ignored: paste them into Agentverse and do not share them.
Full steps: docs/HOSTED.md.
"""

